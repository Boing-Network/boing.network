import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import {
  addBoingPoolLiquidity,
  boingPoolAccessListHex,
  boingPoolBytecodeHex,
  boingPoolEffectiveFeeBps,
  boingPoolMinOutWithSlippage,
  buildBoingPoolCallTransaction,
  createBoingPool,
  quoteBoingPoolAmountOut,
  quoteBoingPoolLpMinted,
  quoteBoingPoolRemove,
  quoteBoingPoolSwap,
  removeBoingPoolLiquidity,
  swapBoingPool,
} from '../src/boingPool.js';
import { signTransactionInput } from '../src/transactionBuilder.js';
import { encodeNativeAmmSetTokensCalldata } from '../src/nativeAmm.js';
import { hexToBytes } from '../src/hex.js';
import type { BoingClient } from '../src/client.js';

/** Generated by `crates/boing-cli/src/pool.rs` tests (public test seed 0x07*32). */
const V = JSON.parse(readFileSync(new URL('./fixtures/pool-cli-vectors.json', import.meta.url), 'utf8'));
const SEED = hexToBytes(V.secretHex);

describe('boing pool SDK helpers: byte-identical to the Rust CLI', () => {
  it('create (deploy v7 + set_tokens + set_fee_admin + set_fee) matches CLI', async () => {
    const r = await createBoingPool(null, SEED, {
      nonce: 0n,
      dryRun: true,
      tokenAHex: V.tokenAHex,
      tokenBHex: V.tokenBHex,
      feeAdminHex: V.recipientHex,
      feeBps: 50n,
    });
    expect(r.deployerHex).toBe(V.senderHex);
    expect(r.poolHex).toBe(V.poolHex);
    expect(r.txs.map((t) => t.signedHex)).toEqual([V.deployV7.signedHex, V.setTokens.signedHex, V.setFeeAdmin.signedHex, V.setFee.signedHex]);
    expect(r.txs[0]!.txId).toBe(V.deployV7.txId);
  });

  it('deploy v1 matches CLI', async () => {
    const r = await createBoingPool(null, SEED, { nonce: 0n, dryRun: true, version: 1 });
    expect(r.txs[0]!.signedHex).toBe(V.deployV1.signedHex);
  });

  it('add / swap / swap_to / remove match CLI', async () => {
    const add = await addBoingPoolLiquidity(null, SEED, { poolHex: V.poolHex, amountA: 10_000n, amountB: 40_000n, minLiquidity: 9_000n, nonce: 4n, dryRun: true });
    expect(add.signedHex).toBe(V.addLiquidity.signedHex);
    const sw = await swapBoingPool(null, SEED, { poolHex: V.poolHex, direction: 'a-to-b', amountIn: 1_000n, minOut: 3_600n, extraAccountsHex: [V.tokenBHex, V.tokenAHex], nonce: 5n, dryRun: true });
    expect(sw.signedHex).toBe(V.swap.signedHex);
    expect(sw.txId).toBe(V.swap.txId);
    const st = await swapBoingPool(null, SEED, { poolHex: V.poolHex, direction: 'b-to-a', amountIn: 2_000n, minOut: 400n, toHex: V.recipientHex, extraAccountsHex: [V.tokenAHex, V.tokenBHex], nonce: 6n, dryRun: true });
    expect(st.signedHex).toBe(V.swapTo.signedHex);
    const rm = await removeBoingPoolLiquidity(null, SEED, { poolHex: V.poolHex, liquidity: 2_500n, minA: 2_000n, minB: 9_000n, extraAccountsHex: [V.tokenAHex, V.tokenBHex], nonce: 7n, dryRun: true });
    expect(rm.signedHex).toBe(V.removeLiquidity.signedHex);
  });

  it('low-level builder agrees with the flow helpers', async () => {
    const tx = buildBoingPoolCallTransaction({ nonce: 1n, senderHex: V.senderHex, poolHex: V.poolHex, calldata: encodeNativeAmmSetTokensCalldata(V.tokenAHex, V.tokenBHex), extraAccountsHex: [V.tokenAHex, V.tokenBHex] });
    expect(await signTransactionInput(tx, SEED)).toBe(V.setTokens.signedHex);
  });

  it('offline dry-run without bounds is refused', async () => {
    await expect(swapBoingPool(null, SEED, { poolHex: V.poolHex, direction: 'a-to-b', amountIn: 1n, nonce: 0n, dryRun: true })).rejects.toThrow(/minOut/);
    await expect(removeBoingPoolLiquidity(null, SEED, { poolHex: V.poolHex, liquidity: 1n, nonce: 0n, dryRun: true })).rejects.toThrow(/minA/);
    await expect(createBoingPool(null, SEED, { nonce: 0n, dryRun: true, version: 3, tokenAHex: V.tokenAHex, tokenBHex: V.tokenBHex })).rejects.toThrow(/token hooks/);
  });
});

describe('boing pool math mirrors the CLI / bytecode', () => {
  it('quotes, fees, slippage, LP math', () => {
    expect(quoteBoingPoolAmountOut(1, 1000n, 2000n, 100n, 30n)).toBe(180n);
    expect(quoteBoingPoolAmountOut(7, 1000n, 2000n, 100n, 30n)).toBe(180n);
    expect(quoteBoingPoolAmountOut(6, 1000n, 2000n, 100n, 2000n)).not.toBe(quoteBoingPoolAmountOut(7, 1000n, 2000n, 100n, 2000n));
    expect(() => quoteBoingPoolAmountOut(1, 1n << 64n, 1n, 1n, 30n)).toThrow(/u64/);
    expect(boingPoolEffectiveFeeBps(7, 0n)).toBe(30n);
    expect(boingPoolEffectiveFeeBps(7, 100n)).toBe(100n);
    expect(boingPoolEffectiveFeeBps(2, 100n)).toBe(30n);
    expect(boingPoolMinOutWithSlippage(1000n, 50n)).toBe(995n);
    expect(boingPoolMinOutWithSlippage(1n, 10_000n)).toBe(1n);
    expect(quoteBoingPoolLpMinted(0n, 0n, 0n, 1000n, 2000n)).toBe(1000n);
    expect(quoteBoingPoolLpMinted(1000n, 2000n, 1000n, 100n, 500n)).toBe(100n);
    expect(quoteBoingPoolRemove(1000n, 2000n, 1000n, 250n)).toEqual([250n, 500n]);
    expect(boingPoolAccessListHex(V.senderHex, V.poolHex, [V.tokenBHex, V.tokenAHex, V.poolHex, `0x${'00'.repeat(32)}`])).toEqual([V.senderHex, V.poolHex, V.tokenAHex, V.tokenBHex]);
    expect(boingPoolBytecodeHex(7).startsWith('0x')).toBe(true);
  });

  it('quoteBoingPoolSwap reads storage and applies fee-on-input for v7', async () => {
    const w = (n: bigint) => ({ value: `0x${n.toString(16).padStart(64, '0')}` });
    const store: Record<string, bigint> = {};
    const key = (b: number) => `0x${'00'.repeat(31)}${b.toString(16).padStart(2, '0')}`;
    store[key(1)] = 10_000n; store[key(2)] = 40_000n; store[key(3)] = 10_000n; store[key(7)] = 0n;
    const client = { getContractStorage: async (_p: string, k: string) => w(store[k.toLowerCase()] ?? 0n) } as unknown as BoingClient;
    const q = await quoteBoingPoolSwap(client, { poolHex: V.poolHex, direction: 'a-to-b', amountIn: 1_000n });
    expect(q.feeBps).toBe(30n);
    expect(q.amountOut).toBe(quoteBoingPoolAmountOut(7, 10_000n, 40_000n, 1_000n, 30n));
    expect(q.minOut).toBe(boingPoolMinOutWithSlippage(q.amountOut, 50n));
  });
});